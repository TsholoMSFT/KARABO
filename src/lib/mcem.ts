/**
 * MCEM pipeline domain model.
 *
 * This is the spine of the distilled app. It models the journey the subsidiary
 * actually cares about:
 *
 *   generate a PIPELINE of candidate use cases
 *     -> account teams (ATU) VALIDATE them with the customer
 *       -> SURVIVING use cases become OPPORTUNITIES that get worked on
 *         -> opportunities progress through MCEM Stage 1 -> 4
 *           -> Stage 4 is the HANDSHAKE to CSU (not CSU delivery work)
 *
 * Stages covered: 1 (ATU) -> 4 (handshake to CSU). The Customer Success work
 * that happens AFTER the handshake is intentionally out of scope.
 *
 * Types + constant metadata live here. Behaviour (gates, transitions,
 * promotion, status derivation) lives in `mcem-engine.ts`.
 */

import type { UseCase } from './types'

